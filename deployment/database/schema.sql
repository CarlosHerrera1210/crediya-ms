-- Esquema de la base de datos para PostgreSQL.
-- Debe coincidir con co.com.crediya.jpa.entity.UserEntity y RoleEntity.

CREATE TABLE IF NOT EXISTS rol (
    id_rol      SERIAL      NOT NULL,
    nombre      VARCHAR(50) NOT NULL,
    descripcion TEXT,
    CONSTRAINT rol_pkey PRIMARY KEY (id_rol),
    CONSTRAINT rol_nombre_key UNIQUE (nombre)
);

INSERT INTO rol (nombre, descripcion) VALUES
    ('ADMIN',   'Administrador del sistema'),
    ('ASESOR',  'Asesor que gestiona las solicitudes de credito'),
    ('CLIENTE', 'Cliente que solicita creditos')
ON CONFLICT (nombre) DO NOTHING;

CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombres             VARCHAR(100)   NOT NULL,
    apellidos           VARCHAR(100)   NOT NULL,
    fecha_nacimiento    DATE,
    direccion           VARCHAR(255),
    telefono            VARCHAR(30),
    correo_electronico  VARCHAR(150)   NOT NULL,
    salario_base        NUMERIC(15, 2) NOT NULL,
    documento_identidad VARCHAR(20),
    id_rol              INTEGER        NOT NULL,
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT uk_usuarios_correo UNIQUE (correo_electronico),
    CONSTRAINT uk_usuarios_documento UNIQUE (documento_identidad),
    CONSTRAINT ck_usuarios_salario CHECK (salario_base BETWEEN 0 AND 15000000),
    CONSTRAINT fk_usuarios_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol)
        ON UPDATE CASCADE ON DELETE RESTRICT
);
